import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
const result = await build({
  entryPoints: ['src/settings.jsx'],
  bundle: true,
  outfile: 'settings.js',
  format: 'iife',
  platform: 'browser',
  target: 'chrome120',
  supported: { 'template-literal': false },
  jsx: 'automatic',
  minify: true,
  metafile: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: {
    js: '/* Generated by npm run build. Edit src/settings.jsx and src/components/ui.jsx. Licenses: THIRD-PARTY-LICENSES.txt. */',
  },
});
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.startsWith('node_modules/')) continue;
  let dir = path.dirname(input);
  while (!fs.existsSync(path.join(dir, 'package.json'))) dir = path.dirname(dir);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  packages.set(pkg.name, { dir, pkg });
}
let notice =
  'Outlook settings bundles browser-only UI dependencies. No Node worker, runtime download or external UI request.\nPlugin source: repository Apache-2.0 LICENSE and NOTICE.\n\n';
notice += fs.readFileSync('src/components/SHADCN-LICENSE.txt', 'utf8') + '\n';
for (const [name, { dir, pkg }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const license = fs.readdirSync(dir).find((name) => /^licen[cs]e(?:\.md|\.txt)?$/i.test(name));
  const licensePath = license ? path.join(dir, license) : `src/licenses/${name}-${pkg.version}.txt`;
  if (!fs.existsSync(licensePath)) throw new Error('Missing license for ' + name);
  notice +=
    `\n${'='.repeat(72)}\n${name} ${pkg.version} (${pkg.license})\nSource: https://www.npmjs.com/package/${name}/v/${pkg.version}\n\n` +
    fs.readFileSync(licensePath, 'utf8') +
    '\n';
}
fs.writeFileSync('THIRD-PARTY-LICENSES.txt', notice.replace(/\r\n/g, '\n').trimEnd() + '\n');
